"""Prune stale untagged GHCR versions for the images, chart, and layer cache.

Every push to main publishes a v0.0.0-g<sha8> image, so untagged manifests
accumulate indefinitely. Deleting them is not as simple as "delete everything
untagged": with buildx attestations enabled, every image we publish is an OCI
index whose per-platform and attestation manifests appear in the GHCR API as
separate, untagged versions. Deleting those breaks the tagged image that
references them — including published releases. cosign signatures are stored
under a sha256-<digest> tag and so are tagged, but the manifests inside them
are not.

So a digest is deletable only when it is BOTH untagged AND unreachable from any
tagged version, after walking every tagged index one level down. Anything we
cannot resolve is treated as reachable: the cost of keeping a stale blob is
storage, the cost of deleting a referenced one is a broken release.

The layer cache in snapshot/cache accumulates the same way and faster. Each
push to main moves cache:<image>-main onto a new manifest and leaves the
previous one untagged, at a size comparable to the image it built. It is pruned
on its own clock, because the two have nothing in common: a published image is
history, while a superseded cache manifest is regenerated by the next push and
is worth nothing the moment the tag leaves it. Nothing ever reads an untagged
cache manifest — --cache-from names tags, and a tag always points at the newest.

Pull request images are the one tagged kind that is deleted. e2e-pr.yaml
publishes the operator, agent, and pagebroker of every mirrored commit as
v0.0.0-pull-request-<number>-g<sha8>, for the GPU suite of that run alone, so a
version whose every tag has that shape expires on its own short clock. Its
child manifests go in the same sweep -- once the index is gone they are
orphans, and waiting out the untagged clock would keep them for a quarter. A
version carrying any other tag is kept, and so is any child a kept version
still references.

Not covered: a cache tag for a branch that no longer exists, which stays tagged
and so is never considered here. One per abandoned release branch.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone

API = "https://api.github.com"
REGISTRY = "https://ghcr.io"

# The tag e2e-pr.yaml publishes pull request images under. Anchored at both
# ends: a looser match is how a release tag would end up deleted.
PR_TAG = re.compile(r"^v0\.0\.0-pull-request-[0-9]+-g[0-9a-f]{8}$")

INDEX_TYPES = {
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
}


def _get(url: str, token: str, accept: str) -> tuple[dict | list | None, dict]:
    req = urllib.request.Request(url, headers={
        "Authorization": f"Bearer {token}",
        "Accept": accept,
        "X-GitHub-Api-Version": "2022-11-28",
    })
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.load(resp), dict(resp.headers)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None, {}
        if exc.code in (401, 403):
            raise PermissionError(
                f"{exc.code} for {url} — the token needs read:packages to list "
                f"versions and packages: write to delete them"
            ) from exc
        raise


def list_versions(org: str, package: str, token: str) -> list[dict]:
    """Every version of one container package, following pagination."""
    out: list[dict] = []
    page = 1
    while True:
        url = (f"{API}/orgs/{org}/packages/container/"
               f"{package.replace('/', '%2F')}/versions?per_page=100&page={page}")
        body, _ = _get(url, token, "application/vnd.github+json")
        if not body:
            break
        out.extend(body)
        if len(body) < 100:
            break
        page += 1
    return out


def registry_token(repo_path: str, token: str) -> str:
    """Exchange the Actions token for a registry pull token."""
    url = f"{REGISTRY}/token?scope=repository:{repo_path}:pull&service=ghcr.io"
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)["token"]


def child_digests(repo_path: str, digest: str, reg_token: str) -> set[str]:
    """Digests referenced by an index. Empty for a plain manifest.

    On any failure the caller treats the parent as opaque and keeps everything,
    so returning an empty set here must never be read as "nothing referenced".
    """
    url = f"{REGISTRY}/v2/{repo_path}/manifests/{digest}"
    accept = ", ".join(sorted(INDEX_TYPES) + [
        "application/vnd.oci.image.manifest.v1+json",
        "application/vnd.docker.distribution.manifest.v2+json",
    ])
    body, headers = _get(url, reg_token, accept)
    if not body:
        raise RuntimeError(f"could not read manifest {digest}")
    if headers.get("Content-Type", "").split(";")[0] in INDEX_TYPES:
        return {m["digest"] for m in body.get("manifests", []) if m.get("digest")}
    return set()


def _created(version: dict) -> datetime:
    return datetime.fromisoformat(version["created_at"].replace("Z", "+00:00"))


def _delete(org: str, package: str, token: str, version: dict, reason: str,
            dry_run: bool) -> bool:
    """Delete one version, or only report it. True when it was deleted."""
    print(f"  {'would delete' if dry_run else 'deleting'} "
          f"{package}@{version.get('name', '')[:19]} "
          f"({reason}, created {_created(version).date()})")
    if dry_run:
        return False
    req = urllib.request.Request(
        f"{API}/orgs/{org}/packages/container/"
        f"{package.replace('/', '%2F')}/versions/{version['id']}",
        method="DELETE",
        headers={"Authorization": f"Bearer {token}",
                 "Accept": "application/vnd.github+json"},
    )
    urllib.request.urlopen(req, timeout=30).close()
    return True


def prune_package(org: str, package: str, token: str, keep_days: int,
                  dry_run: bool, pr_keep_days: int | None = None,
                  pr_dry_run: bool | None = None) -> tuple[int, int]:
    """Prune one package. pr_keep_days None leaves pull request images alone."""
    if pr_dry_run is None:
        pr_dry_run = dry_run
    repo_path = f"{org}/{package}".lower()
    versions = list_versions(org, package, token)
    if not versions:
        print(f"  {package}: no versions visible")
        return (0, 0)

    reg_token = registry_token(repo_path, token)
    now = datetime.now(timezone.utc)
    cutoff = now - timedelta(days=keep_days)
    pr_cutoff = None if pr_keep_days is None else now - timedelta(days=pr_keep_days)

    reachable: set[str] = set()
    untagged: list[dict] = []
    expired: list[tuple[dict, set[str]]] = []
    unresolved = False
    for v in versions:
        tags = (v.get("metadata") or {}).get("container", {}).get("tags") or []
        digest = v.get("name", "")
        if not tags:
            untagged.append(v)
            continue
        is_expired = (pr_cutoff is not None
                      and all(PR_TAG.match(t) for t in tags)
                      and _created(v) <= pr_cutoff)
        if not is_expired:
            reachable.add(digest)
        try:
            children = child_digests(repo_path, digest, reg_token)
        except Exception as exc:  # noqa: BLE001 - see below
            # Marking only the parent reachable would leave its children
            # looking unreferenced, which is exactly how a published image
            # gets its manifests deleted. We cannot enumerate what we could
            # not read, so nothing in this package is safe to delete.
            print(f"  ! {package}@{digest[:19]}: {exc}")
            unresolved = True
            continue
        if is_expired:
            expired.append((v, children))
        else:
            reachable |= children

    if unresolved:
        print(f"  {package}: {len(versions)} versions, "
              f"skipping deletions — a tagged manifest could not be resolved")
        return (len(untagged), 0)

    # An expired image that a kept index still references is kept, and so is
    # everything under it.
    orphaned: set[str] = set()
    for v, children in expired:
        if v.get("name", "") in reachable:
            reachable |= children
        else:
            orphaned |= children
    orphaned -= reachable

    pruned = prunable = 0

    def delete(version: dict, reason: str, report_only: bool) -> None:
        nonlocal pruned, prunable
        if _delete(org, package, token, version, reason, report_only):
            pruned += 1
        else:
            prunable += 1

    # Index first, then the manifests it referenced, so nothing tagged is ever
    # left pointing at a deleted child.
    for v, _ in expired:
        if v.get("name", "") not in reachable:
            delete(v, "expired pull request image", pr_dry_run)
    for v in untagged:
        digest = v.get("name", "")
        if digest in reachable:
            continue
        if digest in orphaned:
            delete(v, "child of an expired pull request image", pr_dry_run)
        elif _created(v) <= cutoff:
            delete(v, "untagged", dry_run)

    print(f"  {package}: {len(versions)} versions, {len(untagged)} untagged, "
          f"{len(expired)} expired pull request, {len(reachable)} reachable, "
          f"{pruned} pruned, {prunable} prunable")
    return (len(untagged), pruned + prunable)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--org", default="ai-dynamo")
    ap.add_argument(
        "--packages",
        default="snapshot/operator,snapshot/agent,snapshot/pagebroker,snapshot/snapshot",
    )
    ap.add_argument("--keep-days", type=int, default=90)
    # The layer cache is pruned on its own, much shorter clock. A published
    # image is history worth keeping for a quarter; a superseded cache manifest
    # is regenerated by the next push to main and worth nothing the moment the
    # tag moves off it, at several gigabytes each.
    ap.add_argument("--cache-packages", default="snapshot/cache")
    ap.add_argument("--cache-keep-days", type=int, default=7)
    # Pull request images are tagged, so the untagged clock never reaches them.
    # They exist for the GPU suite of one e2e-pr.yaml run and have no use after
    # it; a week covers a rerun or a look at a failure.
    ap.add_argument("--pr-keep-days", type=int, default=7)
    ap.add_argument("--dry-run", default="true")
    # Defaults to --dry-run. Separate so that expiring pull request images can
    # run for real while the untagged sweep is still reporting only.
    ap.add_argument("--pr-dry-run", default=None)
    args = ap.parse_args()

    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        print("GITHUB_TOKEN is not set", file=sys.stderr)
        return 1

    dry_run = args.dry_run.lower() != "false"
    pr_dry_run = dry_run if args.pr_dry_run is None else args.pr_dry_run.lower() != "false"
    print(f"org={args.org} keep_days={args.keep_days} "
          f"cache_keep_days={args.cache_keep_days} pr_keep_days={args.pr_keep_days} "
          f"dry_run={dry_run} pr_dry_run={pr_dry_run}")

    total = 0
    try:
        # The cache never holds pull request images, so it is not swept for them.
        for spec, keep_days, pr_keep_days in (
                (args.packages, args.keep_days, args.pr_keep_days),
                (args.cache_packages, args.cache_keep_days, None)):
            for package in [p.strip() for p in spec.split(",") if p.strip()]:
                _, deleted = prune_package(args.org, package, token, keep_days, dry_run,
                                           pr_keep_days=pr_keep_days,
                                           pr_dry_run=pr_dry_run)
                total += deleted
    except PermissionError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print(f"{'Prunable' if dry_run else 'Pruned'}: {total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
