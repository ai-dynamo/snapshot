def svg(name, width, height, title, desc, body):
    doc = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n'
        '     SPDX-License-Identifier: Apache-2.0 -->\n'
        '<!-- Generated by generate.py: edit the script, not this file. -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0f}" height="{height:.0f}" '
        f'viewBox="0 0 {width:.0f} {height:.0f}" role="img" aria-labelledby="title desc">\n'
        f'<title id="title">{escape(title)}</title>\n<desc id="desc">{escape(desc)}</desc>\n'
        f'<style>{CSS}</style>\n{MARKERS}\n'
        f'<rect class="bg" x="0.5" y="0.5" width="{width - 1:.0f}" height="{height - 1:.0f}" rx="10"/>\n'
        + "\n".join(body)
        + "\n</svg>\n"
    )
    with open(os.path.join(HERE, name), "w") as f:
        f.write(doc)


def T(x, y, s, cls, size=13, bold=False, anchor="middle"):
    weight = 700 if bold else 400
    return (
        f'<text x="{x:.1f}" y="{y:.1f}" class="{cls}" font-size="{size}" '
        f'font-weight="{weight}" text-anchor="{anchor}" dominant-baseline="central">'
        f"{escape(s)}</text>"
    )


def box(x, y, w, h, kind, title, sub=None, rx=8):
    out = [f'<rect class="k-{kind}" x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" rx="{rx}" stroke-width="0.8"/>']
    cx = x + w / 2
    if sub:
        out.append(T(cx, y + h / 2 - 9, title, f"k-{kind}-t", 14, True))
        out.append(T(cx, y + h / 2 + 10, sub, f"k-{kind}-s", 12))
    else:
        out.append(T(cx, y + h / 2, title, f"k-{kind}-t", 14, True))
    return out


def line(x1, y1, x2, y2, cls="arw", marker="ah", dash=None, both=False, width=1.2):
    d = f' stroke-dasharray="{dash}"' if dash else ""
    start = f' marker-start="url(#{marker})"' if both else ""
    end = f' marker-end="url(#{marker})"' if marker else ""
    return f'<line class="{cls}" x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke-width="{width}"{d}{start}{end}/>'


def path(d, cls="arw", marker="ah", dash=None, width=1.2):
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<path class="{cls}" d="{d}" fill="none" stroke-width="{width}"{da} marker-end="url(#{marker})"/>'


# ---------------------------------------------------------------------------
# Sequence diagrams
#
# Steps:
#   ("m", from, to, label[, reply])  message; reply=1 draws a dashed arrow
#   ("s", actor, label)              action on one lifeline
#   ("n", a, b, label)               note spanning two lifelines
#   ("g", label) / ("e", label)      frame (alt, par) and its else branch
#   ("r", label)                     round band, the pattern of figure 3
#   ("x",)                           closes the innermost frame or band
# ---------------------------------------------------------------------------


def sequence(name, title, desc, actors, steps, width=900):
    W, M, FS, LH = width, 20, 13, 16
    n = len(actors)
    col = (W - 2 * M) / n
    bw = min(col - 14, 160)
    X = {a[0]: M + col * (i + 0.5) for i, a in enumerate(actors)}
    K = {a[0]: a[3] for a in actors}
    parts, frames, stack = [], [], []
    y = 80

    for st in steps:
        kind = st[0]
        if kind == "m":
            src, dst, label = st[1], st[2], st[3]
            reply = len(st) > 4 and st[4]
            x1, x2 = X[src], X[dst]
            avail = max(abs(x2 - x1) - 24, 290)
            lines = wrap(label, avail, FS)
            lw = max(tw(s, FS) for s in lines)
            cx = min(max((x1 + x2) / 2, M + lw / 2 + 6), W - M - lw / 2 - 6)
            y += 4
            for i, s in enumerate(lines):
                parts.append(T(cx, y + i * LH + LH / 2, s, "tx", FS))
            y += len(lines) * LH + 4
            step = 1 if x2 > x1 else -1
            parts.append(line(x1, y, x2 - step * 2, y, dash="5 4" if reply else None))
            y += 8
        elif kind == "s":
            actor, label = st[1], st[2]
            k = K[actor]
            lines = wrap(label, 230, FS)
            w = max(tw(s, FS) for s in lines) + 26
            h = len(lines) * LH + 12
            bx = min(max(X[actor] - w / 2, M), W - M - w)
            y += 6
            parts.append(f'<rect class="k-{k}" x="{bx:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h}" rx="5" stroke-width="0.8"/>')
            for i, s in enumerate(lines):
                parts.append(T(bx + w / 2, y + 6 + i * LH + LH / 2, s, f"k-{k}-t", FS))
            y += h + 8
        elif kind == "n":
            xa, xb = sorted((X[st[1]], X[st[2]]))
            w = min(max(xb - xa + 140, 320), W - 2 * M)
            x0 = max(M, min((xa + xb) / 2 - w / 2, W - M - w))
            lines = wrap(st[3], w - 28, 12)
            h = len(lines) * 16 + 12
            y += 6
            parts.append(f'<rect class="note" x="{x0:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h}" rx="5" stroke-width="0.8"/>')
            for i, s in enumerate(lines):
                parts.append(T(x0 + w / 2, y + 6 + i * 16 + 8, s, "notet", 12))
            y += h + 8
        elif kind in ("g", "r"):
            y += 8
            stack.append({"kind": kind, "y0": y, "label": st[1], "elses": []})
            y += 32
        elif kind == "e":
            y += 8
            stack[-1]["elses"].append((y, st[1]))
            y += 30
        elif kind == "x":
            frame = stack.pop()
            y += 8
            frame["y1"] = y
            frame["depth"] = len(stack)
            frames.append(frame)
            y += 6
    assert not stack, f"{name}: unclosed frame"

    bottom = y + 14
    H = bottom + 62
    body = []
    # Round bands sit behind everything else.
    for f in frames:
        if f["kind"] != "r":
            continue
        x0, x1 = 10 + f["depth"] * 9, W - 10 - f["depth"] * 9
        body.append(f'<rect class="rnd" x="{x0}" y="{f["y0"]:.1f}" width="{x1 - x0}" height="{f["y1"] - f["y0"]:.1f}" rx="6" stroke-width="0.8"/>')
    for a in actors:
        body.append(line(X[a[0]], 62, X[a[0]], bottom + 2, cls="life", marker=None, dash="4 4", width=1))
    for f in frames:
        x0, x1 = 10 + f["depth"] * 9, W - 10 - f["depth"] * 9
        tag_w = tw(f["label"], 12, True) + 20
        if f["kind"] == "g":
            body.append(f'<rect class="frm" x="{x0}" y="{f["y0"]:.1f}" width="{x1 - x0}" height="{f["y1"] - f["y0"]:.1f}" rx="6" stroke-width="1"/>')
            body.append(f'<rect class="tag" x="{x0}" y="{f["y0"]:.1f}" width="{tag_w:.1f}" height="22" rx="5" stroke-width="0.8"/>')
            body.append(T(x0 + 10, f["y0"] + 11, f["label"], "tagt", 12, True, "start"))
            for ey, label in f["elses"]:
                body.append(line(x0, ey, x1, ey, cls="frm", marker=None, dash="6 4", width=1))
                body.append(T(x0 + 10, ey + 13, label, "tagt", 12, True, "start"))
        else:
            body.append(f'<rect class="rndtag" x="{x0}" y="{f["y0"]:.1f}" width="{tag_w:.1f}" height="22" rx="5" stroke-width="0.8"/>')
            body.append(T(x0 + 10, f["y0"] + 11, f["label"], "rndt", 12, True, "start"))
    body.extend(parts)
    for a in actors:
        key, label, sub, k = a
        for top in (14, bottom + 6):
            body.extend(box(X[key] - bw / 2, top, bw, 48, k, label, sub or None, rx=7))
    svg(name, W, H, title, desc, body)


