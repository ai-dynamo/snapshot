"""Generate the SVG diagrams of SNEP-324.

Run `python3 generate.py` from any directory; it rewrites every *.svg next to
this file. Sequence diagrams are plain data (actors and steps) rendered by
`sequence()`, so a change to a flow is an edit to its step list. Text widths
are measured with Liberation Sans, which is metric-compatible with Arial and
Helvetica, and fall back to an estimate when that font is not installed.
"""

import os
from xml.sax.saxutils import escape

try:
    from PIL import ImageFont
except ImportError:  # pragma: no cover - the estimate below is good enough
    ImageFont = None

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = {
    False: "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    True: "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
}
_font_cache = {}


def tw(text, size, bold=False):
    """Rendered width of text, with a small safety margin."""
    key = (size, bold)
    if key not in _font_cache:
        font = None
        if ImageFont is not None:
            try:
                font = ImageFont.truetype(FONTS[bold], size)
            except OSError:
                font = None
        _font_cache[key] = font
    font = _font_cache[key]
    if font is None:
        return len(text) * size * (0.6 if bold else 0.55)
    return font.getlength(text) * 1.06


def wrap(text, width, size, bold=False):
    lines, cur = [], ""
    for word in text.split(" "):
        cand = cur + " " + word if cur else word
        if cur and tw(cand, size, bold) > width:
            lines.append(cur)
            cur = word
        else:
            cur = cand
    if cur:
        lines.append(cur)
    return lines


