func TestRestoreIPMap(t *testing.T) {
	tests := []struct {
		name     string
		sourceIP string
		targetIP string
		peers    string
		want     string
		wantErr  string
	}{
		{name: "own address", sourceIP: "10.0.0.11", targetIP: "10.1.4.21", want: "10.0.0.11=10.1.4.21"},
		{
			name:     "own address and peers",
			sourceIP: "10.0.0.11",
			targetIP: "10.1.4.21",
			peers:    "10.0.0.13=10.1.4.23,10.0.0.12=10.1.4.22",
			want:     "10.0.0.11=10.1.4.21,10.0.0.12=10.1.4.22,10.0.0.13=10.1.4.23",
		},
		{name: "unknown own address keeps the peers", targetIP: "10.1.4.21", peers: "10.0.0.12=10.1.4.22", want: "10.0.0.12=10.1.4.22"},
		{name: "peer repeats the own mapping", sourceIP: "10.0.0.11", targetIP: "10.1.4.21", peers: "10.0.0.11=10.1.4.21", want: "10.0.0.11=10.1.4.21"},
		{
			name:     "IPs swapped between members",
			sourceIP: "10.0.0.11",
			targetIP: "10.0.0.12",
			peers:    "10.0.0.12=10.0.0.11",
			want:     "10.0.0.11=10.0.0.12,10.0.0.12=10.0.0.11",
		},
		{name: "peer moves the own address elsewhere", sourceIP: "10.0.0.11", targetIP: "10.1.4.21", peers: "10.0.0.11=10.1.4.99", wantErr: "a peer mapping moves it to 10.1.4.99"},
		{name: "two members move to one IP", sourceIP: "10.0.0.11", targetIP: "10.1.4.21", peers: "10.0.0.12=10.1.4.21", wantErr: "both move to 10.1.4.21"},
		{name: "invalid source", sourceIP: "not-an-ip", targetIP: "10.1.4.21", wantErr: "invalid source pod IP"},
		{name: "invalid target", sourceIP: "10.0.0.11", targetIP: "not-an-ip", wantErr: "invalid target pod IP"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var peers IPMap
			if err := peers.Set(tt.peers); err != nil {
				t.Fatalf("peers: %v", err)
			}
			m := &types.CheckpointManifest{K8s: types.SourcePodManifest{PodIP: tt.sourceIP}}
			got, err := RestoreIPMap(m, tt.targetIP, peers)
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("RestoreIPMap error = %v, want %q", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("RestoreIPMap: %v", err)
			}
			if got.String() != tt.want {
				t.Fatalf("RestoreIPMap = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestConfigureInetRemapWritesGroupMappings(t *testing.T) {
	tests := []struct {
		name    string
		ipMap   string
		want    string
		wantErr string
	}{
		{
			name:  "every changed IP, sorted",
			ipMap: "10.0.0.13=10.1.4.23,10.0.0.11=10.1.4.21,10.0.0.12=10.1.4.22",
			want:  "# generated by Snapshot\n10.0.0.11 10.1.4.21\n10.0.0.12 10.1.4.22\n10.0.0.13 10.1.4.23\n",
		},
		{
			name:  "unchanged IPs are left out",
			ipMap: "10.0.0.11=10.0.0.11,10.0.0.12=10.1.4.22",
			want:  "# generated by Snapshot\n10.0.0.12 10.1.4.22\n",
		},
		{name: "IPv6 peer", ipMap: "10.0.0.11=10.1.4.21,fd00::1=fd00::2", wantErr: "only supports IPv4"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			m := remapManifest(t)
			var ipMap IPMap
			if err := ipMap.Set(tt.ipMap); err != nil {
				t.Fatalf("ipMap: %v", err)
			}
			t.Setenv(InetRemapEnvVar, "")
			err := ConfigureInetRemap(m, ipMap, testr.New(t))
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("ConfigureInetRemap error = %v, want %q", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("ConfigureInetRemap: %v", err)
			}
			content, err := os.ReadFile(os.Getenv(InetRemapEnvVar))
			if err != nil {
				t.Fatalf("ReadFile: %v", err)
			}
			if string(content) != tt.want {
				t.Fatalf("remap content = %q, want %q", content, tt.want)
			}
		})
	}
}

func TestIPMapFlagRefusesMalformedValues(t *testing.T) {
	var ipMap IPMap
	for _, bad := range []string{"10.0.0.12", "x=10.1.4.22", "10.0.0.12=y", "10.0.0.12=10.1.4.22,", "10.0.0.12=10.1.4.22,10.0.0.12=10.1.4.23"} {
		if err := ipMap.Set(bad); err == nil {
			t.Errorf("Set(%q) succeeded, want an error", bad)
		}
	}
}

// podIPMap returns the IP map of a restore of m onto targetPodIP, without peers.
func podIPMap(t *testing.T, m *types.CheckpointManifest, targetPodIP string) IPMap {
	t.Helper()
	ipMap, err := RestoreIPMap(m, targetPodIP, nil)
	if err != nil {
		t.Fatalf("RestoreIPMap: %v", err)
	}
	return ipMap
}

func remapManifest(t *testing.T) *types.CheckpointManifest {
	return &types.CheckpointManifest{
		CRIUDump: types.CRIUDumpManifest{
			CRIU: types.CRIUSettings{
				LibDir:         "/usr/local/lib/snapshot/criu-plugins",
				TcpEstablished: true,
				WorkDir:        t.TempDir(),
			},
		},
	}
}
